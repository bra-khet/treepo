/// `identity.json`, as written.
///
/// Field order is the order a person reads them in: what this is, then why, then when.
#[derive(Debug, Serialize, Deserialize)]
struct StoredIdentity {
    version: u32,
    /// The plain sentence answering "why did these two checkouts share a store?".
    ///
    /// Written for people and never read back — [`Resolution`] carries the structured form.
    #[serde(default, skip_deserializing)]
    explanation: String,
    key: String,
    tier: String,
    source_value: String,
    resolved_at: u64,
    /// The same instant as `resolved_at`, spelled for a human. Written, never read.
    #[serde(default, skip_deserializing)]
    resolved_at_utc: String,
    derivation: StoredDerivation,
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct StoredDerivation {
    /// The remote tier 1 used, by name.
    chosen_remote: Option<String>,
    /// Every remote considered, in name order. Normalized only — a raw URL can carry a
    /// credential, and `resolve` strips them before anything reaches this file.
    remotes: Vec<StoredRemote>,
    /// The root commit, when tier 2 resolved one.
    root_commit: Option<String>,
    /// Why each tier above the winning one did not apply.
    skipped: Vec<StoredSkip>,
}

#[derive(Debug, Serialize, Deserialize)]
struct StoredRemote {
    name: String,
    normalized_url: Option<String>,
}

#[derive(Debug, Serialize, Deserialize)]
struct StoredSkip {
    /// A stable machine name, so a later release can act on this without parsing prose.
    code: String,
    /// The sentence a user reads.
    #[serde(default, skip_deserializing)]
    reason: String,
}

impl From<&Resolution> for StoredIdentity {
    fn from(resolution: &Resolution) -> Self {
        let Resolution {
            identity,
            remotes,
            chosen,
            root_commit,
            skipped,
        } = resolution;
        Self {
            version: FORMAT_VERSION,
            explanation: explain(identity),
            key: identity.directory_name(),
            tier: tier_name(identity.tier).to_string(),
            source_value: identity.source_value.clone(),
            resolved_at: identity.resolved_at,
            resolved_at_utc: utc_timestamp(identity.resolved_at),
            derivation: StoredDerivation {
                chosen_remote: chosen.clone(),
                remotes: remotes
                    .iter()
                    .map(|remote| {
                        let RemoteUrl { name, normalized } = remote;
                        StoredRemote {
                            name: name.clone(),
                            normalized_url: normalized.clone(),
                        }
                    })
                    .collect(),
                root_commit: root_commit.map(|id| id.to_string()),
                skipped: skipped
                    .iter()
                    .map(|skip| StoredSkip {
                        code: skip_code(*skip).to_string(),
                        reason: skip.reason().to_string(),
                    })
                    .collect(),
            },
        }
    }
}

impl StoredIdentity {
    fn into_resolution(self, path: &std::path::Path) -> Result<Resolution, IdentityError> {
        let malformed = |detail: String| IdentityError::Malformed {
            path: path.to_path_buf(),
            detail,
        };

        let tier = tier_from_name(&self.tier)
            .ok_or_else(|| malformed(format!("unknown identity tier `{}`", self.tier)))?;
        // Recomputed rather than trusted: the key is *defined* as the hash of the two fields
        // above it, and a file claiming otherwise has been edited.
        let identity = RepoIdentity::new(tier, self.source_value, self.resolved_at);
        if identity.directory_name() != self.key {
            return Err(IdentityError::Inconsistent {
                detail: format!(
                    "its key is not the hash of its own tier and source value — recorded {}, \
                     computed {}",
                    self.key,
                    identity.directory_name()
                ),
            });
        }

        let mut skipped = Vec::with_capacity(self.derivation.skipped.len());
        for skip in self.derivation.skipped {
            skipped.push(
                skip_from_code(&skip.code)
                    .ok_or_else(|| malformed(format!("unknown skip code `{}`", skip.code)))?,
            );
        }

        Ok(Resolution {
            identity,
            remotes: self
                .derivation
                .remotes
                .into_iter()
                .map(|remote| RemoteUrl {
                    name: remote.name,
                    normalized: remote.normalized_url,
                })
                .collect(),
            chosen: self.derivation.chosen_remote,
            root_commit: self
                .derivation
                .root_commit
                .map(|hex| commit_from_hex(&hex))
                .transpose()
                .map_err(malformed)?,
            skipped,
        })
    }
}

/// The sentence `F-MAN-3` asks this file to make answerable.
fn explain(identity: &RepoIdentity) -> String {
    match identity.tier {
        IdentityTier::Remote => format!(
            "Identified by its remote URL, so every clone of {} shares this store — including \
             one at a different path, and one on a different branch.",
            identity.source_value
        ),
        IdentityTier::RootCommit => {
            "Identified by its first commit, because it has no remote configured. Moving or \
             renaming the folder keeps this store; a fork or a copy with the same history \
             shares it."
                .to_string()
        }
        IdentityTier::PathHash => format!(
            "Identified by its location, {}, because there was no remote and no commit to \
             identify it by. Moving the folder will start a new store.",
            identity.source_value
        ),
    }
}

// Names rather than numbers, written out in both directions. A `Serialize` derive on
// `IdentityTier` would put a variant name in the file and tie the format to a Rust
// identifier; writing them here means renaming a variant is a Rust refactor and renaming a
// stored value is a format decision.

const fn tier_name(tier: IdentityTier) -> &'static str {
    match tier {
        IdentityTier::Remote => "remote-url",
        IdentityTier::RootCommit => "root-commit",
        IdentityTier::PathHash => "path-hash",
    }
}

fn tier_from_name(name: &str) -> Option<IdentityTier> {
    match name {
        "remote-url" => Some(IdentityTier::Remote),
        "root-commit" => Some(IdentityTier::RootCommit),
        "path-hash" => Some(IdentityTier::PathHash),
        _ => None,
    }
}

const fn skip_code(skipped: Skipped) -> &'static str {
    match skipped {
        Skipped::NoRepository => "no-repository",
        Skipped::NoRemotes => "no-remotes",
        Skipped::NoRemoteUrl => "no-remote-url",
        Skipped::NoCommits => "no-commits",
        Skipped::TruncatedHistory => "truncated-history",
        Skipped::NoRootCommit => "no-root-commit",
    }
}

fn skip_from_code(code: &str) -> Option<Skipped> {
    match code {
        "no-repository" => Some(Skipped::NoRepository),
        "no-remotes" => Some(Skipped::NoRemotes),
        "no-remote-url" => Some(Skipped::NoRemoteUrl),
        "no-commits" => Some(Skipped::NoCommits),
        "truncated-history" => Some(Skipped::TruncatedHistory),
        "no-root-commit" => Some(Skipped::NoRootCommit),
        _ => None,
    }
}

fn commit_from_hex(hex: &str) -> Result<CommitId, String> {
    let bytes: Result<Vec<u8>, String> = hex
        .as_bytes()
        .chunks(2)
        .map(|pair| {
            std::str::from_utf8(pair)
                .ok()
                .and_then(|pair| u8::from_str_radix(pair, 16).ok())
                .ok_or_else(|| format!("`{hex}` is not a hexadecimal object id"))
        })
        .collect();
    let bytes = bytes?;
    match bytes.len() {
        20 => Ok(CommitId::sha1(bytes.try_into().unwrap_or([0; 20]))),
        32 => Ok(CommitId::sha256(bytes.try_into().unwrap_or([0; 32]))),
        other => Err(format!("object id is {other} bytes, not 20 or 32")),
    }
}

/// `YYYY-MM-DDThh:mm:ssZ` for a Unix timestamp, by integer arithmetic alone.
///
/// Howard Hinnant's `civil_from_days`, which is exact for every date this will ever see. A
/// date library would be a dependency for one cosmetic field, and a float would be `N3`'s
/// problem in a file that is otherwise beyond its reach.
fn utc_timestamp(seconds: u64) -> String {
    let days = (seconds / 86_400) as i64;
    let time = seconds % 86_400;

    // Shift the epoch to 0000-03-01 so leap days land at the end of the year.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let day_of_era = z.rem_euclid(146_097);
    let year_of_era =
        (day_of_era - day_of_era / 1_460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let shifted_month = (5 * day_of_year + 2) / 153;

    let day = day_of_year - (153 * shifted_month + 2) / 5 + 1;
    let month = if shifted_month < 10 {
        shifted_month + 3
    } else {
        shifted_month - 9
    };
    let year = year_of_era + era * 400 + i64::from(month <= 2);

    format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}Z",
        time / 3_600,
        (time % 3_600) / 60,
        time % 60
    )
}

