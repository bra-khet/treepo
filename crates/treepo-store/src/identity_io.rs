    /// A store directory copied under another name is not that other repository's store.
    ///
    /// The realistic route to this is a user copying an app-data directory between machines
    /// and renaming one by hand. Trusting the file over the directory would hand them one
    /// repository's tree under another repository's name.
    #[test]
    fn an_identity_in_the_wrong_directory_is_refused() {
        let dir = std::env::temp_dir()
            .join("treepo-identity-io")
            .join("wrong-directory");
        if dir.exists() {
            std::fs::remove_dir_all(&dir).expect("clearing scratch");
        }
        let root = StoreRoot::at(dir);

        let real = resolution(IdentityTier::Remote);
        let real_store = root.repository(&real.identity);
        write(&real_store, &real).expect("the write");

        // A second, genuine store for a different repository — then the first one's file
        // copied into it, which is exactly what a hand-copied directory looks like.
        let other = RepoIdentity::new(
            IdentityTier::Remote,
            "github.com/someone/other".to_string(),
            0,
        );
        let impostor = root.repository(&other);
        assert_ne!(impostor.dir(), real_store.dir());
        std::fs::create_dir_all(impostor.dir()).expect("the other directory");
        std::fs::copy(real_store.identity_file(), impostor.identity_file()).expect("the copy");

        let error = read(&impostor).expect_err("it names a different repository");
        assert!(matches!(error, IdentityError::Inconsistent { .. }));
        assert!(error.is_regenerable());
        assert!(error.to_string().contains("sitting in"));
        // And the original still reads, so the check is about placement, not the file.
        assert_eq!(read(&real_store).expect("still fine"), real);
    }

