//! `identity.json` — which repository this store belongs to, and why (`F-MAN-2`, `F-MAN-3`).
//!
//! > `identity.json` records both the resolved key and which tier produced it, so a user can
//! > see why two checkouts did or did not share a store.
//!
//! That sentence is the whole specification, and it is a *user-facing* one: the file exists to
//! be opened and understood, not merely to be parsed. So it is JSON (`N2`, architecture D9),
//! it is pretty-printed, the tier is a word rather than a number, the timestamp is written
//! twice — once as seconds and once as a date a person can read — and it carries a plain
//! sentence saying what the identity means for sharing.
//!
//! # This file is a new one
//!
//! The architecture's file tree names `manifest_io.rs` and `world_io.rs` but no
//! `identity_io.rs`, while still requiring `identity.json` to exist. Reading that as an
//! oversight rather than a decision: persistence lives in `*_io.rs` in this crate, and
//! [`resolve`](crate::resolve) is documented as pure — a normalized URL is a function of a
//! string, and keeping it that way is what makes it exhaustively testable without a
//! filesystem.
//!
//! # Nothing here is trusted
//!
//! A user can edit this file; `N2` invites them to look at it, and looking leads to editing.
//! So [`read`] recomputes the key from the tier and source value it finds and rejects a file
//! whose stored key disagrees, and rejects one sitting in a directory it does not name. The
//! consequence of trusting it would be a store that serves one repository's tree for another.
//!
//! Nothing is lost by refusing: the identity is a function of the repository and is
//! regenerated by opening it (`F-MAN-8`).

use crate::manifest_io::{WriteError, write_atomically};
use crate::paths::RepositoryStore;
use crate::resolve::{RemoteUrl, Resolution, Skipped};
use serde::{Deserialize, Serialize};
use std::path::PathBuf;
use treepo_model::identity::{CommitId, IdentityTier, RepoIdentity};

/// The version of this file's shape.
///
/// Not `F-MAN-6`'s schema version, which is the manifest's. This one moves when the *fields*
/// here change, and a file at any other version is regenerated rather than read — the same
/// answer, for the same reason, at a hundredth of the cost.
const FORMAT_VERSION: u32 = 1;

/// Why a stored identity could not be read.
#[derive(Debug)]
pub enum IdentityError {
    /// No `identity.json` here. An ordinary first open (`F-MAN-8`).
    Absent,
    /// The filesystem refused.
    Io {
        /// The file being read.
        path: PathBuf,
        /// What it said.
        source: std::io::Error,
    },
    /// Not JSON, not this format's version, or a field this build does not understand.
    Malformed {
        /// The file that was read.
        path: PathBuf,
        /// What was wrong.
        detail: String,
    },
    /// The file parsed and then contradicted itself.
    ///
    /// A key that is not the hash of the tier and source value beside it, or an identity in a
    /// directory named after a different one. Both mean the file was edited or moved, and both
    /// are worth distinguishing from a parse failure — this one says the *store* is wrong
    /// rather than the file.
    Inconsistent {
        /// What did not add up.
        detail: String,
    },
}

impl std::fmt::Display for IdentityError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Absent => write!(f, "no identity recorded yet"),
            Self::Io { path, source } => write!(f, "reading {}: {source}", path.display()),
            Self::Malformed { path, detail } => {
                write!(f, "{} is not readable: {detail}", path.display())
            }
            Self::Inconsistent { detail } => {
                write!(f, "the stored identity does not add up: {detail}")
            }
        }
    }
}

impl std::error::Error for IdentityError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Io { source, .. } => Some(source),
            _ => None,
        }
    }
}

impl IdentityError {
    /// Whether the right response is to resolve the identity again.
    ///
    /// True for everything but an I/O failure — resolving costs a config read, so there is
    /// never a reason to limp along with a file that does not make sense.
    #[must_use]
    pub const fn is_regenerable(&self) -> bool {
        !matches!(self, Self::Io { .. })
    }
}

/// Writes `identity.json` into `store`, atomically (`F-MAN-2`, `F-MAN-7`).
///
/// # Errors
///
/// [`WriteError`] if the directory cannot be created or the file cannot be written.
pub fn write(store: &RepositoryStore, resolution: &Resolution) -> Result<(), WriteError> {
    let mut text =
        serde_json::to_string_pretty(&StoredIdentity::from(resolution)).unwrap_or_default();
    text.push('\n');
    write_atomically(&store.identity_file(), text.as_bytes())
}

/// Reads the identity `store` records, checking it against itself and against its directory.
///
/// # Errors
///
/// [`IdentityError::Absent`] when there is none — the ordinary first open. See
/// [`IdentityError::is_regenerable`] for the rest.
pub fn read(store: &RepositoryStore) -> Result<Resolution, IdentityError> {
    let path = store.identity_file();
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(source) if source.kind() == std::io::ErrorKind::NotFound => {
            return Err(IdentityError::Absent);
        }
        Err(source) => return Err(IdentityError::Io { path, source }),
    };

    let stored: StoredIdentity =
        serde_json::from_str(&text).map_err(|error| IdentityError::Malformed {
            path: path.clone(),
            detail: error.to_string(),
        })?;
    if stored.version != FORMAT_VERSION {
        return Err(IdentityError::Malformed {
            path,
            detail: format!(
                "written in format {} and this build reads {FORMAT_VERSION}",
                stored.version
            ),
        });
    }

    let resolution = stored.into_resolution(&path)?;
    let directory = store
        .dir()
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or_default();
    if directory != resolution.identity.directory_name() {
        return Err(IdentityError::Inconsistent {
            detail: format!(
                "it names a repository whose store is {}, but it is sitting in {directory}",
                resolution.identity.directory_name()
            ),
        });
    }
    Ok(resolution)
}

/// Wall-clock seconds, for [`RepoIdentity::resolved_at`].
///
/// **The only clock reading in the product's own crates.** `N3` bans `SystemTime::now`
/// workspace-wide because a generated value that depends on when it was generated destroys
/// `AC-DET-1`; this one is store housekeeping — how `F-MAN-9`'s browser shows a last-opened
/// time — and it is confined here so that "does treepo read the clock, and where" has one
/// answer that can be checked.
///
/// It is not hashed into the identity key, and `treepo-model` states the same rule from the
/// other side: nothing in `treepo-gen` or `treepo-grow` may read `resolved_at`.
///
/// Zero before 1970, which no filesystem will produce and which is a better answer than a
/// panic in a housekeeping field.
#[must_use]
#[expect(
    clippy::disallowed_methods,
    clippy::disallowed_types,
    reason = "N3's one sanctioned clock read, narrowed to this function; see the doc comment"
)]
pub fn now() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::SystemTime::UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_secs())
}

